class P6_PositiveNegativeOrZero {
    public static void main(String[] args) {

		int num = 0; // input num

		// condition to check +ve -ve zero
		if(num > 0) {
			System.out.println("Your number is: " + num + " which is Positive number");
		}
		else if(num < 0) {
			System.out.println("Your number is: " + num + " which is Negative number");
		}
		else {
			System.out.println("Your number is: " + num + " which is Zero");
		}
    }
}

