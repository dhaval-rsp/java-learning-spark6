class P1_SimpleCalculator {
    public static void main(String[] args) {

		int a = 22; // integer 1
		int b = 3; // integer 2

		int addition = a + b; // addition
		int subtraction = b - a; // subtraction
		int multiplication = a * b; // multiplication
		int division = a / b; // division
		int remainder = a % b; // remainder

		// printing all output
		System.out.println("The Addition of " + a + " & " + b + " is: " + addition);
		System.out.println("The Subtraction of " + a + " & " + b + " is: " + subtraction);
		System.out.println("The Multiplication of " + a + " & " + b + " is: " + multiplication);
		System.out.println("The Division of " + a + " & " + b + " is: " + division);
		System.out.println("The Remainder of " + a + " & " + b + " is: " + remainder);
    }
}

